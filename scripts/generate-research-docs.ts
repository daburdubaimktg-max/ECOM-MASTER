function marketplaceDoc() {
  const dir = path.join(RESEARCH, 'marketplaces');
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  const order = ['AE', 'SA', 'ZA', 'US', 'GB', 'IN', 'KE', 'NG', 'MY'];
  const countries = files
    .map((f) => countryFileSchema.parse(JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))))
    .sort((a, b) => order.indexOf(a.country_code) - order.indexOf(b.country_code));

  // Sensitivity view: the same researcher scores, but ignoring how easy the data is to obtain.
  const CATEGORY_LED = { ecommerce_significance: 0.2, beauty_category_relevance: 0.4, consumer_reach: 0.2, brand_competitor_coverage: 0.2, data_integration_feasibility: 0 } as const;
  const categoryLed = (scores: Record<string, { score: number }>) =>
    Math.round(PRIORITY_CRITERIA.reduce((sum, c) => sum + scores[c].score * CATEGORY_LED[c], 0) * 100) / 100;

  let total = 0;
  const sensitivity: string[] = [];
  const summaryRows: string[] = [];
  const sections: string[] = [];
  const appendix: Record<string, string> = {
    AE: 'B1-marketplaces-uae-saudi-malaysia.md',
    SA: 'B1-marketplaces-uae-saudi-malaysia.md',
    MY: 'B1-marketplaces-uae-saudi-malaysia.md',
    ZA: 'B2-marketplaces-south-africa-kenya-nigeria.md',
    KE: 'B2-marketplaces-south-africa-kenya-nigeria.md',
    NG: 'B2-marketplaces-south-africa-kenya-nigeria.md',
    US: 'B3-marketplaces-us-uk-india.md',
    GB: 'B3-marketplaces-us-uk-india.md',
    IN: 'B3-marketplaces-us-uk-india.md',
  };

  for (const country of countries) {
    const platforms = country.platforms
      .map((p) => ({ ...p, name: displayPlatformName(p.name), score: weightedPriorityScore(p.priority_scores), alt: categoryLed(p.priority_scores) }))
      .sort(
        (a, b) =>
          b.score - a.score ||
          b.priority_scores.beauty_category_relevance.score - a.priority_scores.beauty_category_relevance.score ||
          b.priority_scores.consumer_reach.score - a.priority_scores.consumer_reach.score ||
          a.name.localeCompare(b.name),
      );
    total += platforms.length;
    const top3 = platforms.slice(0, 3);
    const altTop3 = [...platforms].sort((a, b) => b.alt - a.alt || b.score - a.score).slice(0, 3);
    const changed = altTop3.map((p) => p.name).join('|') !== top3.map((p) => p.name).join('|');
    summaryRows.push(`| **${country.country_name}** | ${top3.map((p) => `${p.name} (${p.score.toFixed(2)})`).join(' | ')} | ${platforms.length} |`);
    if (new Set(altTop3.map((p) => p.name)).size && altTop3.some((p) => !top3.some((t) => t.name === p.name))) {
      const entering = altTop3.filter((p) => !top3.some((t) => t.name === p.name)).map((p) => p.name);
      const leaving = top3.filter((p) => !altTop3.some((t) => t.name === p.name)).map((p) => p.name);
      sensitivity.push(`${country.country_name} (${entering.join(', ')} would replace ${leaving.join(', ')})`);
    } else if (changed) {
      sensitivity.push(`${country.country_name} (same three, different order: ${altTop3.map((p) => p.name).join(', ')})`);
    }

    sections.push(`## ${country.country_name}

${country.market_context.summary}

**Key facts** (each labelled with what kind of number it is)

${country.market_context.key_facts
  .slice(0, 6)
  .map((f) => `- ${cell(f.fact, 400)} — *${f.nature.replace(/_/g, ' ')}*${/^https?:/.test(f.source_url) ? `; [${cell(f.source_name, 70)}](${f.source_url})` : ''}`)
  .join('\n')}

**Ranked platforms**

| Rank | Platform | Kind | Business model | Beauty relevance | Main data route | Score /5 | Confidence |
|:-:|---|---|---|:-:|---|:-:|:-:|
${platforms
  .map(
    (p, i) =>
      `| ${i < 3 ? `**${i + 1}**` : i + 1} | ${i < 3 ? `**${p.name}**` : p.name}${p.status !== 'active' ? ` *(${p.status.replace('_', ' ')})*` : ''} | ${PLATFORM_CATEGORY_LABELS[p.platform_category]} | ${MARKETPLACE_TYPE_LABELS[p.marketplace_type]} | ${p.beauty_relevance ?? '—'} | ${DATA_ACCESS_LABELS[p.data_access_method]}${p.api_availability.public_seller_api === 'yes' ? ' · public seller API' : ''} | ${p.score.toFixed(2)} | ${p.confidence} |`,
  )
  .join('\n')}

**Why the top three**

${top3.map((p, i) => `${i + 1}. **${p.name}** — ${cell(p.priority_rationale ?? p.priority_scores.beauty_category_relevance.note, 900)}`).join('\n')}

**If data access is ignored** (ranking on market and category importance only): ${altTop3.map((p) => `${p.name} (${p.alt.toFixed(2)})`).join(', ')}.${changed ? ' This differs from the main ranking — see the note on reading the rankings.' : ' The top three are the same.'}

${country.ranking_method_note ? `**Researcher's note:** ${cell(country.ranking_method_note, 900)}\n` : ''}
Full evidence, excluded platforms and sources: [Appendix ${appendix[country.country_code].slice(0, 2)}](appendix/${appendix[country.country_code]}) · data file: \`data/research/marketplaces/${country.country_code}.json\`
`);
  }

  write(
    'docs/research/03-global-marketplace-research.md',
    `${GENERATED}

# Deliverable 3 — Global Marketplace Research

**Research date:** 26 November 2026 · **Countries:** ${countries.length} · **Platforms recorded:** ${total} · **Loaded into the product:** yes — see *Marketplace Intelligence* in the app

For each of the nine launch markets this report identifies the online platforms that matter for mass-market beauty and personal care (hair, skin and oral care), ranks them with a transparent method, and names the three to prioritise. Every platform record carries its evidence, sources and a confidence level; the same records power the Marketplace Intelligence screens.

## The top three in each market

| Market | 1st | 2nd | 3rd | Platforms researched |
|---|---|---|---|:-:|
${summaryRows.join('\n')}

Scores are out of 5 and are **calculated priority scores, not market shares**.

## How platforms were ranked

Each platform was scored 1–5 on five criteria, with a written evidence note for every score. The weighted total sets the rank; ties go to the platform with the higher beauty relevance, then the larger reach.

| Criterion | Weight | The question it answers |
|---|:-:|---|
${PRIORITY_CRITERIA.map((c) => `| ${PRIORITY_CRITERIA_LABELS[c].label} | ${Math.round(PRIORITY_WEIGHTS[c] * 100)}% | ${PRIORITY_CRITERIA_LABELS[c].question} |`).join('\n')}

The product **recalculates every score and rank from the stored criterion scores** when it loads the data, and an automated test fails if a stored rank ever differs from the recalculated one. Nobody types a rank in by hand.

## How to read the rankings — four cautions

1. **These are priorities for monitoring, not a league table of sales.** No platform's market share is verified by a regulator or audited filing in any of the nine markets. Reach figures are web-traffic estimates (Semrush, Similarweb), company statements or analyst estimates, and are labelled as such on every record. Traffic estimates from different providers differ by up to two or three times, and they understate app-first platforms.
2. **Amazon is not ranked first automatically — but the formula does reward reach and data access.** One fifth of the score is "can we legitimately get the data?". That lifts platforms with a documented seller API (Amazon, Takealot, Shopee, Lazada) and lowers specialists whose sites refuse automated access. Each country section therefore also shows the order *if data access is ignored*. That changes the picture in: ${sensitivity.join('; ') || 'no country'}. The researchers added three judgements of their own that the formula does not capture: on category relevance alone **Boots** (UK) and **Nykaa** (India) would rank first; **Nahdi** probably sells more of this category online than Amazon.sa; and Amazon.co.za's second place in South Africa reflects data access, not category leadership — **Clicks** is the category leader there. Specialists like these should be tracked by whatever legitimate route exists (distributor reports, retailer-supplied data, manual checks) even where they rank lower here.
3. **Brand coverage could not be checked on sites that block automated access** (about 18 in the Gulf and Malaysia alone; Walmart, Boots, Tesco, Nykaa, Clicks, Dis-Chem and others elsewhere). Those records say so and carry lower confidence. Nothing was done to get round a block.
4. **Research is a snapshot.** African e-commerce in particular changes quickly. Re-research at least twice a year; the product keeps every earlier version as history.

${sections.join('\n---\n\n')}

---

## The marketplace database

Each platform record contains the fields the specification asked for: name, country, region, website, platform category, marketplace type, beauty relevance, pharmacy relevance, estimated market importance, consumer-reach evidence, competitor presence, product coverage, data access method, API availability, data-collection feasibility, source citations, last research date, confidence level and priority ranking. In the product they live in the \`marketplaces\`, \`marketplace_evidence\`, \`marketplace_sources\`, \`country_research\` and \`marketplace_research_snapshots\` tables ([database schema](../architecture/database-schema.md)).

To add or update research, see "Updating marketplace research" in the [how-to guide](../guides/how-to.md).

## Limitations

- The shared web-search allowance for this research session ran out part-way; later checks used direct retrieval of known pages, so some ownership and status facts are marked UNVERIFIED in the data.
- Scores are informed judgements against a rubric, not measurements. They are transparent and reproducible, and can be re-weighted.
- Social commerce (WhatsApp, Instagram, TikTok) is a major route for beauty in Kenya and Nigeria and is under-represented because it cannot be evidenced in the same way.
- D2C and brand-owned sites are described in the appendices rather than ranked.
`,
  );
}

