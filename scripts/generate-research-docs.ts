const cell = (value: unknown, max = 220): string => {
  const text = String(value ?? '').replace(/\s+/g, ' ').replace(/\|/g, '/').trim();
  if (!text) return '—';
  return text.length > max ? `${text.slice(0, max - 1).trimEnd()}…` : text;
};
