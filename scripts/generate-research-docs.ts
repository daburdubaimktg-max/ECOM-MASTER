const snake = (name: string) => name.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`);

function schemaDoc() {
  const tables = new Map<string, ReturnType<typeof getTableConfig>>();
  for (const value of Object.values(schema)) {
    if (value && typeof value === 'object' && Symbol.for('drizzle:IsDrizzleTable') in (value as object)) {
      const config = getTableConfig(value as PgTable);
      tables.set(config.name, config);
    }
  }
  const documented = new Set(MODULES.flatMap((m) => m.tables));
  const missing = [...tables.keys()].filter((t) => !documented.has(t));
  if (missing.length) throw new Error(`Tables missing from the schema document: ${missing.join(', ')}`);

  const sections = MODULES.map((module) => {
    const body = module.tables
      .map((name) => {
        const config = tables.get(name);
        if (!config) throw new Error(`Unknown table ${name}`);
        const fks = new Map<string, string>();
        for (const fk of config.foreignKeys) {
          const ref = fk.reference();
          ref.columns.forEach((col, i) => fks.set(snake(col.name), `${getTableConfig(ref.foreignTable as PgTable).name}.${snake(ref.foreignColumns[i].name)}`));
        }
        const rows = config.columns
          .map((col) => `| \`${snake(col.name)}\` | ${col.getSQLType()} | ${col.primary ? 'primary key' : col.notNull ? 'required' : 'optional'} | ${fks.get(snake(col.name)) ? `→ \`${fks.get(snake(col.name))}\`` : ''} |`)
          .join('\n');
        return `#### \`${name}\`\n\n| Column | Type | | Links to |\n|---|---|---|---|\n${rows}\n`;
      })
      .join('\n');
    return `## ${module.title}\n\n*${module.status}.* ${module.note}\n\n${body}`;
  });

  write(
    'docs/architecture/database-schema.md',
    `${GENERATED}

# Database schema reference

**Tables:** ${tables.size} · **Engine:** PostgreSQL 15+ with the pgvector and pg_trgm extensions · **Source of truth:** \`src/db/schema/*.ts\` · **Migrations:** \`drizzle/*.sql\`

This is the complete relational design for Phase 1 of the Brand Intelligence Engine. It was created in full in the first build so that later modules plug in without restructuring; the status line under each heading says which parts are in use today.

## Design rules that apply to every table

1. **Everything belongs to an organisation.** Business tables carry \`organisation_id\`; every query in the application is scoped by it, and brand-level access is applied on top for restricted users.
2. **Observations are never overwritten.** Listing snapshots, prices, availability, ratings, scores and research are append-only: new information is a new row with its own timestamp.
3. **Every marketplace observation records where it came from:** data source, collection method, collection time, confidence, the raw observation and the processed result — stored separately.
4. **Five data classes are kept apart:** verified, calculated, AI-assessed, estimated and missing. A missing observation is recorded as missing (\`outcome\`, \`availability\`), never as zero or "unavailable".
5. **Scores are reproducible.** An internal score row points at the exact snapshot and the exact version of the scoring rule that produced it, and stores a hash of its inputs.
6. **Official scores are never fabricated.** A row in \`official_quality_scores\` exists only when the score was obtained through an authorised route.
7. **The audit log is append-only at database level:** a trigger rejects any direct UPDATE or DELETE on \`audit_logs\`.
8. **No reviewer identities are stored** — only a one-way fingerprint used to detect duplicate reviews.
9. **Secrets never live in the database.** \`data_sources.configuration\` holds non-secret settings only; credentials belong in environment variables or a secrets manager.

${sections.join('\n')}
`,
  );
}

